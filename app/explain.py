TODO_ORDER = ["R5", "R3", "R6", "TI", "R4", "R1", "R2", "R7", "AI"]


def build_story(result: dict) -> dict:
    ips = result["ips"]
    levels = result["summary"]["levels"]
    total_flagged = result["summary"]["flagged"]
    n_ips = result["summary"]["ips"]

    if not total_flagged:
        return {
            "mood": "calm",
            "headline": "수상한 접속을 찾지 못했어요",
            "sub": f"방문한 {n_ips:,}곳(IP)의 기록을 모두 살펴봤는데, 공격으로 의심되는 행동이 없었어요.",
            "todo": [],
            "by_rule": [],
        }

    # 유형별로 몇 곳에서 나왔는지
    counts: dict[str, int] = {}
    for ip in ips:
        for rule in {f["rule"] for f in ip["findings"]}:
            counts[rule] = counts.get(rule, 0) + 1
    rule_counts = {r: c for r, c in counts.items() if r != "AI"} or counts   # 'AI'는 행동 이름이 아니라서 되도록 빼고 고른다
    top_rule = max(rule_counts, key=lambda r: (rule_counts[r], -TODO_ORDER.index(r)))

    high = levels.get("높음", 0)
    mood = "alert" if high else "worried"
    if high:
        sub = f"그중 {high}곳은 바로 확인이 필요해요. 가장 많이 보인 행동은 ‘{RULES[top_rule]['easy']}’이에요."
    else:
        sub = f"바로 위험한 곳은 없지만 살펴볼 곳이 있어요. 가장 많이 보인 행동은 ‘{RULES[top_rule]['easy']}’이에요."

    todo = []
    for rule in TODO_ORDER:
        if rule in counts:
            todo.append({"rule": rule, "title": RULES[rule]["todo"],
                         "why": RULES[rule]["todo_why"], "count": counts[rule]})
    by_rule = sorted(({"rule": r, "easy": RULES[r]["easy"], "count": c}
                      for r, c in counts.items()), key=lambda x: (-x["count"], TODO_ORDER.index(x["rule"])))
    return {
        "mood": mood,
        "by_rule": by_rule,
        "headline": f"{total_flagged}곳에서 수상한 접속을 찾았어요",
        "sub": sub,
        "todo": todo[:4],
        "more_todo": max(0, len(todo) - 4),
    }
